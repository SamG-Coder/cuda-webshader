typedef struct
{
    float4 m[3];
} float3x4;

__constant__ float3x4 c_invViewMatrix; // inverse view matrix

__device__ float3 mul(const float3x4 &M, const float3 &v)
{
    float3 r;
    r.x = dot(v, make_float3(M.m[0]));
    r.y = dot(v, make_float3(M.m[1]));
    r.z = dot(v, make_float3(M.m[2]));
    return r;
}

// transform vector by matrix with translation
__device__ float4 mul(const float3x4 &M, const float4 &v)
{
    float4 r;
    r.x = dot(v, M.m[0]);
    r.y = dot(v, M.m[1]);
    r.z = dot(v, M.m[2]);
    r.w = 1.0f;
    return r;
}


// Project validation entry, MIT. NVIDIA helpers above are unchanged.
__global__ void transformProbe(const float4* input, float4* output){
 float4 point=input[0];
 output[0]=make_float4(mul(c_invViewMatrix,make_float3(point)),0.0f);
 output[1]=mul(c_invViewMatrix,point);
}
